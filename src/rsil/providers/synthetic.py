"""Deterministic synthetic corpus.

Generated by this repository, so it carries no third-party rights: it exists to
prove the pipeline end to end and to serve as the CI fixture. Every row is
flagged is_synthetic=True and no real club, player or price is represented.
"""
import hashlib

from .base import ProviderResult, SourceMeta

LICENCE = "CC0-1.0"
LICENCE_URL = "https://creativecommons.org/publicdomain/zero/1.0/"


def _h(*parts) -> int:
    return int(hashlib.sha256("|".join(parts).encode()).hexdigest()[:8], 16)


class SyntheticProvider:
    def __init__(self, competitions=2, seasons=2, teams_per_competition=6,
                 retrieved_at="2026-11-25T00:00:00+00:00", complete=True):
        self.competitions = competitions
        self.seasons = seasons
        self.teams = teams_per_competition
        self.retrieved_at = retrieved_at
        self.complete = complete
        self.meta = SourceMeta(
            name="synthetic",
            licence=LICENCE,
            licence_url=LICENCE_URL,
            attribution="Generated by rsil.providers.synthetic (no real data)",
            source_url="https://github.com/Isokex/ron-sports-intelligence-lab",
            retrieved_at=retrieved_at,
            permitted={"research": True, "production_training": True,
                       "redistribution": True},
        )

    def fetch(self) -> ProviderResult:
        rows = []
        for c in range(self.competitions):
            comp_id = f"syn-comp-{c}"
            for s in range(self.seasons):
                season = str(2023 + s)
                for home in range(self.teams):
                    for away in range(self.teams):
                        if home == away:
                            continue
                        mid = f"{comp_id}-{season}-{home:02d}{away:02d}"
                        hs = _h(mid, "h") % 4
                        as_ = _h(mid, "a") % 4
                        day = 1 + (_h(mid, "d") % 27)
                        month = 1 + (_h(mid, "m") % 12)
                        kickoff = f"{season}-{month:02d}-{day:02d}T15:00:00+00:00"
                        rows.append({
                            "competition_id": comp_id,
                            "competition_name": f"Synthetic League {c}",
                            "season": season,
                            "match_id": mid,
                            "kickoff_utc": kickoff,
                            "status": "FT",
                            "home_team_id": f"{comp_id}-t{home}",
                            "home_team_name": f"Synthetic {c} Team {home}",
                            "away_team_id": f"{comp_id}-t{away}",
                            "away_team_name": f"Synthetic {c} Team {away}",
                            "home_goals": hs, "away_goals": as_,
                            "ht_home_goals": min(hs, _h(mid, "hh") % 3),
                            "ht_away_goals": min(as_, _h(mid, "ha") % 3),
                            "shots_home": 5 + _h(mid, "sh") % 15,
                            "shots_away": 5 + _h(mid, "sa") % 15,
                            "shots_on_target_home": 1 + _h(mid, "sth") % 8,
                            "shots_on_target_away": 1 + _h(mid, "sta") % 8,
                            "xg_home": round(0.4 + (_h(mid, "xh") % 200) / 100, 2),
                            "xg_away": round(0.3 + (_h(mid, "xa") % 200) / 100, 2),
                            "odds_home": round(1.4 + (_h(mid, "oh") % 300) / 100, 2),
                            "odds_draw": round(2.8 + (_h(mid, "od") % 200) / 100, 2),
                            "odds_away": round(1.4 + (_h(mid, "oa") % 300) / 100, 2),
                            "odds_captured_at": kickoff.replace("15:00:00", "14:00:00"),
                            "available_at": kickoff.replace("15:00:00", "17:05:00"),
                            "source_name": "synthetic",
                            "source_record_id": mid,
                            "source_url": "",
                            "ingested_at": self.retrieved_at,
                            "is_synthetic": True,
                        })
        notes = [] if self.complete else ["simulated partial fetch"]
        return ProviderResult(records=rows, complete=self.complete,
                              meta=self.meta, notes=notes)
